"""Phase 23 §3 — read-only release preflight.

Answers one question for the operator: *if this machine's environment were
the production environment, would the service start, and would it be safe
to expose?*

STRICTLY READ-ONLY. This command:
  - never prints a secret value (names, presence and lengths only);
  - never connects to production services and never sends email;
  - never modifies a database (the configured DB is opened `mode=ro`);
  - never creates scanner or staff accounts and never changes credentials;
  - performs no deployment.

Exit code: 0 when no check FAILs, 1 otherwise. BLOCKED means a decision or
credential that only the institution/hosting provider can supply — it is a
visible gate, not a pass, and it deliberately does NOT fail the exit code so
that a config-only rehearsal can still be run. A missing production secret
is a FAIL, never a fallback.

Usage:
    python scripts\\preflight.py
    python scripts\\preflight.py --json
"""

import json
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import config  # noqa: E402

PASS, FAIL, BLOCKED, NOT_TESTED = "PASS", "FAIL", "BLOCKED", "NOT TESTED"
RESULTS = []


def report(area, status, detail):
    RESULTS.append({"area": area, "status": status, "detail": detail})
    print("  %-6s %-26s %s" % (status, area, detail))


def env_set(name):
    return bool((os.environ.get(name) or "").strip())


def _secret_shape(name):
    """Structural description of a secret — NEVER its value."""
    raw = os.environ.get(name) or ""
    if not raw.strip():
        return "unset"
    return "set, %d chars" % len(raw)


# --------------------------------------------------------------------------
def check_secrets():
    print("\n[1] Production secret configuration")
    still_demo = config.demo_secrets()
    if still_demo:
        # Correct, deliberate refusal — the service will not start. Reported
        # as FAIL because it is an unmet precondition, not a decision.
        report("demo-secret protection", PASS,
               "enforced: run.py exits 1 while %s hold committed demo values"
               % ", ".join(still_demo))
        report("operator secrets present", FAIL,
               "still demo: %s (names only). Set real values; no fallback "
               "is generated by this tool." % ", ".join(still_demo))
    else:
        report("demo-secret protection", PASS, "enforced and satisfied")
        report("operator secrets present", PASS, "all three supplied by the operator")

    for name, minimum, note in (
        ("LGU_SECRET_KEY", 32, "signs the staff session cookie + recovery HMAC"),
        ("LGU_HMAC_SECRET", 32, "signs every issued QR code"),
    ):
        raw = os.environ.get(name) or ""
        if not raw.strip():
            report(name, FAIL, "unset (%s)" % note)
        elif len(raw) < minimum:
            report(name, FAIL, "too short: %d chars, %d required (%s)"
                   % (len(raw), minimum, note))
        else:
            report(name, PASS, "present, %d chars (value not shown)" % len(raw))

    pin = os.environ.get("LGU_ADMIN_PIN") or ""
    if not pin.strip():
        report("LGU_ADMIN_PIN", FAIL, "unset (gates broadcasts and settings)")
    elif not pin.isdigit() or not (4 <= len(pin) <= 8):
        report("LGU_ADMIN_PIN", FAIL,
               "must be 4-8 digits (value not shown); currently %s"
               % _secret_shape("LGU_ADMIN_PIN"))
    else:
        report("LGU_ADMIN_PIN", PASS, "present, %d digits (value not shown)"
               % len(pin))


# --------------------------------------------------------------------------
def check_email():
    print("\n[2] Email provider configuration (structural only — no connection)")
    import emailer
    mode = config.EMAIL_MODE
    if mode == "disabled":
        report("LGU_EMAIL_MODE", BLOCKED,
               "disabled: signup and password recovery return HTTP 503 until "
               "an operator supplies SMTP settings")
    elif mode == "fake":
        report("LGU_EMAIL_MODE", FAIL,
               "'fake' is test-suite only and emailer refuses it on the "
               "production database")
    else:
        report("LGU_EMAIL_MODE", PASS, "smtp")

    problems = emailer.smtp_problems()
    if problems:
        for p in problems:
            report("email structure", FAIL, p)
    else:
        report("email structure", PASS,
               "host/port/TLS/from/user-password pairing and TTL all valid "
               "(values not shown)")


# --------------------------------------------------------------------------
def check_cookie_cors_csrf():
    print("\n[3] Cookie, CSRF, CORS and rate limits")
    if config.COOKIE_SECURE:
        report("cookie Secure", PASS, "LGU_COOKIE_SECURE is on (TLS deployment)")
    else:
        report("cookie Secure", BLOCKED,
               "off: correct for a plain-HTTP LAN, MUST be set if this "
               "release is ever fronted by TLS")

    try:
        from web import routes
        factory = routes.create_app
        # The hardening is applied inside create_app (Phase 20 §4). Prove the
        # guard code is present without constructing an application object.
        with open(routes.__file__, "r", encoding="utf-8") as fh:
            src = fh.read()
    except Exception as exc:  # pragma: no cover - import failure is the finding
        report("cookie/CSRF/CORS wiring", FAIL, "web.routes unreadable: %s" % type(exc).__name__)
        return
    del factory

    for label, needle in (
        ("session cookie HttpOnly", "SESSION_COOKIE_HTTPONLY=True"),
        ("session cookie SameSite", 'SESSION_COOKIE_SAMESITE="Lax"'),
        ("session cookie Secure wiring", "SESSION_COOKIE_SECURE=config.COOKIE_SECURE"),
        ("CORS allowlist (no wildcard)", "_origin_allowed"),
    ):
        report(label, PASS if needle in src else FAIL,
               "present in web.routes" if needle in src else
               "MISSING from web.routes — enforcement absent")

    print("\n[4] Rate limits (effective values)")
    for label, window, maximum in (
        ("staff/admin PIN", config.PIN_RATE_WINDOW_SECONDS, config.PIN_RATE_MAX_FAILS),
        ("exam admin login", config.EXAM_RATE_WINDOW_SECONDS, config.EXAM_RATE_MAX_FAILS),
        ("scanner login", config.SCANNER_RATE_WINDOW_SECONDS, config.SCANNER_RATE_MAX_FAILS),
        ("student verify", config.STUDENT_RATE_WINDOW_SECONDS, config.STUDENT_RATE_MAX_VERIFY),
        ("student login", config.STUDENT_RATE_WINDOW_SECONDS, config.STUDENT_RATE_MAX_LOGIN),
        ("pass issue", config.PASS_ISSUE_RATE_WINDOW_SECONDS, config.PASS_ISSUE_RATE_MAX),
    ):
        ok = window > 0 and maximum > 0
        report(label, PASS if ok else FAIL,
               "%d attempts / %ds" % (maximum, window))


# --------------------------------------------------------------------------
def check_database():
    print("\n[5] Database path and schema compatibility (read-only)")
    path = config.DB_PATH
    production = config.is_production_db(path)
    report("configured database",
           BLOCKED if production else PASS,
           "%s (%s)" % ("PRODUCTION" if production else "non-production", path))

    if not os.path.exists(path):
        report("database file", FAIL, "missing: %s" % path)
        return
    try:
        # Read-only URI: the configured database is never opened for write by
        # this tool. urllib handles any special characters in the path.
        import urllib.request
        uri = "file:" + urllib.request.pathname2url(os.path.abspath(path)) + "?mode=ro"
        conn = sqlite3.connect(uri, uri=True, timeout=config.sqlite_busy_timeout())
        try:
            version = conn.execute("PRAGMA user_version").fetchone()[0]
            integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
            tables = conn.execute(
                "SELECT count(*) FROM sqlite_master WHERE type='table'").fetchone()[0]
        finally:
            conn.close()
    except sqlite3.Error as exc:
        report("database readable", FAIL, "%s: %s" % (type(exc).__name__, exc))
        return
    report("database readable", PASS, "opened mode=ro, %d bytes, %d tables"
           % (os.path.getsize(path), tables))
    report("integrity", PASS if integrity == "ok" else FAIL, str(integrity))
    import migrations
    supported = max(v for v, _ in migrations.MIGRATIONS)
    if version > supported:
        report("schema version", FAIL,
               "user_version=%d is NEWER than this build supports (%d)"
               % (version, supported))
    elif version < supported:
        report("schema version", BLOCKED,
               "user_version=%d, build supports %d — %d migration(s) still "
               "pending (see docs/OPERATIONS.md)" % (version, supported, supported - version))
    else:
        report("schema version", PASS, "user_version=%d (current)" % version)


# --------------------------------------------------------------------------
def check_commands():
    print("\n[6] Operational commands discoverable")
    here = os.path.dirname(os.path.abspath(__file__))
    for label, filename, purpose in (
        ("backup CLI", "backup_db.py", "create / verify / restore / list"),
        ("scanner provisioning", "manage_scanner_staff.py", "create / revoke scanner identities"),
        ("staff provisioning", "manage_exam_staff.py", "create staff accounts"),
        ("email config check", "check_email_config.py", "validate SMTP without sending"),
    ):
        found = os.path.exists(os.path.join(here, filename))
        report(label, PASS if found else FAIL,
               "scripts/%s (%s)" % (filename, purpose) if found else
               "scripts/%s MISSING — %s unavailable" % (filename, purpose))

    try:
        import backup
        with open(backup.__file__, "r", encoding="utf-8") as fh:
            refuses = "is_production_db" in fh.read()
        report("restore destination guard", PASS if refuses else FAIL,
               "restore() refuses the production path" if refuses else
               "no production-path refusal found in backup.py")
        report("backup method", PASS,
               "online backup API (conn.backup) — WAL-safe, non-blocking")
    except Exception as exc:  # pragma: no cover
        report("backup module", FAIL, "import failed: %s" % type(exc).__name__)


# --------------------------------------------------------------------------
def check_test_flags():
    print("\n[7] Test-only flags in the intended production configuration")
    for name in ("LGU_TESTING", "LGU_ALLOW_DEMO_SECRETS"):
        if env_set(name):
            report(name, FAIL,
                   "ENABLED — this flag exists only for test harnesses and "
                   "must not be set on a production host")
        else:
            report(name, PASS, "not set")
    if env_set("LGU_DB_PATH"):
        override = os.environ["LGU_DB_PATH"]
        if config.is_production_db(override):
            report("LGU_DB_PATH", FAIL, "overrides the database onto PRODUCTION")
        else:
            report("LGU_DB_PATH", PASS, "points at a non-production file")
    else:
        report("LGU_DB_PATH", PASS, "not set (default app/lgu.db)")


# --------------------------------------------------------------------------
def check_hosting_decisions():
    print("\n[8] Decisions still required from the institution / host")
    report("TLS termination", BLOCKED,
           "decide plain-HTTP LAN vs TLS; sets LGU_COOKIE_SECURE")
    report("SMTP credentials", BLOCKED,
           "real provider credentials are not present in this environment")
    report("event-day capacity approval", BLOCKED,
           "no institutional concurrency estimate or response-time target "
           "has been supplied — synthetic benchmarks are not an SLA")
    report("authorized migration operator", BLOCKED,
           "production schema is behind the build; an authorized operator "
           "must approve and execute the runbook")


# --------------------------------------------------------------------------
def main():
    if "--json" not in sys.argv:
        print("LGU Smart Convocation — release preflight (read-only)")
        print("database target: %s" % config.DB_PATH)
        print("NOTE: no secret values are printed by this tool.")
    check_secrets()
    check_email()
    check_cookie_cors_csrf()
    check_database()
    check_commands()
    check_test_flags()
    check_hosting_decisions()

    counts = {s: sum(1 for r in RESULTS if r["status"] == s)
              for s in (PASS, FAIL, BLOCKED, NOT_TESTED)}
    failed = counts[FAIL] > 0
    print("\nPREFLIGHT: %d PASS, %d FAIL, %d BLOCKED, %d NOT TESTED"
          % (counts[PASS], counts[FAIL], counts[BLOCKED], counts[NOT_TESTED]))
    print("PREFLIGHT RESULT: %s" % ("FAIL" if failed else "PASS (subject to BLOCKED items)"))
    if "--json" in sys.argv:
        print(json.dumps({"results": RESULTS, "counts": counts}, indent=2))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
